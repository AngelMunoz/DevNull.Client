let geometryCache = new ConcurrentDictionary<Glyph, StreamGeometry>()

let geometry glyph =
  geometryCache.GetOrAdd(
    glyph,
    fun glyph -> StreamGeometry.Parse(pathData glyph)
  )

let iconAt(glyph: Glyph, size: float) : PathIcon =
  let icon = PathIcon()

  icon.Height <- size
  icon.Width <- size
  icon.Data <- geometry glyph
  icon

let icon glyph = iconAt(glyph, 18.0)
